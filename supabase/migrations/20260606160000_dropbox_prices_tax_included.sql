-- ============================================================================
-- Dropbox のプリセット価格を税込に統一する
-- ----------------------------------------------------------------------------
-- 背景: Dropbox 公式の表記は税抜。実際の請求は税込（消費税 10%）のため、
--       支出管理の実額に合わせて全 Dropbox プランを税込価格へ更新する。
--       併せて、一時的に追加した重複プラン「Plus（月払い・税込）」を削除する。
-- 設計書: docs/DATABASE_DESIGN.md
-- ============================================================================

-- 1. 重複プラン（Plus 月払い・税込 ¥1,650）を削除
--    参照していたユーザーのサブスクは既存の Plus（月払い）へ張り替え済み。
DELETE FROM plans WHERE id = 'b2000001-0001-4001-8001-000000000301';

-- 2. Dropbox の全プランを税込（×1.1）へ更新
UPDATE plans p
SET price = ROUND(p.price * 1.1, 2)
FROM services s
WHERE p.service_id = s.id
  AND s.name = 'Dropbox';
