-- ============================================================================
-- 重複サービスを参照するテスト契約の付け替え＋重複サービス削除
-- ----------------------------------------------------------------------------
-- 背景: マイグレーション管理外で手動投入された旧プリセット（誤service 33333333・
--   誤plan 44444444）を、test@test.com の契約（55555555）が参照していたため、
--   先行クリーンアップ（20260609120000）の安全策で削除されず重複が残っていた。
--
-- 対応: 契約を正しいプリセット（b2000001-…）へ付け替え（非破壊）、その後に
--   参照の無くなった誤plan・誤serviceを削除する。
--
-- 冪等性: 対象は固定UUIDの手動投入データのみ。ローカル/新規環境には存在しない
--   ため、各文は該当行が無ければ no-op。
-- 設計書: docs/DATABASE_DESIGN.md
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) 契約の付け替え（誤plan -> 価格・名称が最も近い正plan）
--   Netflix Premium(1490)  -> Netflix プレミアム
--   Amazon Prime(600)      -> プライム（月間）(600・一致)
--   DAZN Standard(4200)    -> DAZNスタンダード（月額更新）(4200・一致)
-- ----------------------------------------------------------------------------
UPDATE subscriptions
SET plan_id = 'b2000001-0001-4001-8001-000000000003'
WHERE plan_id = '44444444-0000-0000-0000-000000000001';

UPDATE subscriptions
SET plan_id = 'b2000001-0001-4001-8001-000000000009'
WHERE plan_id = '44444444-0000-0000-0000-000000000002';

UPDATE subscriptions
SET plan_id = 'b2000001-0001-4001-8001-000000000018'
WHERE plan_id = '44444444-0000-0000-0000-000000000003';

-- ----------------------------------------------------------------------------
-- 2) 参照の無くなった誤plan を削除
-- ----------------------------------------------------------------------------
DELETE FROM plans p
WHERE p.id IN (
  '44444444-0000-0000-0000-000000000001',
  '44444444-0000-0000-0000-000000000002',
  '44444444-0000-0000-0000-000000000003'
)
AND NOT EXISTS (
  SELECT 1 FROM subscriptions s WHERE s.plan_id = p.id
);

-- ----------------------------------------------------------------------------
-- 3) 配下プランが無くなった誤service を削除（重複解消）
-- ----------------------------------------------------------------------------
DELETE FROM services
WHERE id IN (
  '33333333-0000-0000-0000-000000000001',
  '33333333-0000-0000-0000-000000000002',
  '33333333-0000-0000-0000-000000000003'
)
AND NOT EXISTS (
  SELECT 1 FROM plans p WHERE p.service_id = services.id
);
