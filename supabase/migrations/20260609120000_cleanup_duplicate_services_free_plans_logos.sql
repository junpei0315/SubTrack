-- ============================================================================
-- プリセットマスタのクリーンアップ
-- ----------------------------------------------------------------------------
-- 1) 重複サービス（マイグレーション管理外で手動投入された旧テストデータ）と配下プランを削除
-- 2) 無料プラン（price = 0）を削除（金額不定のプレースホルダは除外）
-- 3) Figma / Gemini のロゴを同梱画像（logo_key）方式へ統一
--
-- いずれも subscriptions.plan_id は ON DELETE RESTRICT のため、実契約が参照する
-- 行は壊さないよう NOT EXISTS で保護している（参照があれば残す）。
-- 設計書: docs/DATABASE_DESIGN.md
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) 重複サービス削除
--   正: b1000001-...（logo_key・正しいカテゴリあり / preset seed 由来）
--   誤: 33333333-...（手動投入・分類誤り・ロゴ無し）と配下プラン 44444444-...
--   plans.service_id は ON DELETE CASCADE だが、誤プランを参照する実契約があれば
--   RESTRICT で全体が失敗するため、先に未参照のプランのみ明示削除する。
-- ----------------------------------------------------------------------------
DELETE FROM plans p
WHERE p.service_id IN (
  '33333333-0000-0000-0000-000000000001',
  '33333333-0000-0000-0000-000000000002',
  '33333333-0000-0000-0000-000000000003'
)
AND NOT EXISTS (
  SELECT 1 FROM subscriptions s WHERE s.plan_id = p.id
);

DELETE FROM services
WHERE id IN (
  '33333333-0000-0000-0000-000000000001',
  '33333333-0000-0000-0000-000000000002',
  '33333333-0000-0000-0000-000000000003'
)
AND NOT EXISTS (
  SELECT 1 FROM plans p WHERE p.service_id = services.id
);

-- ----------------------------------------------------------------------------
-- 2) 無料プラン削除
--   price = 0 は支出管理上の意味が薄く、代表プラン（最安）選択で ¥0 表示の原因になる。
--   ただし「月会費（店舗により異なる）」は無料ではなく金額不定のプレースホルダのため除外。
-- ----------------------------------------------------------------------------
DELETE FROM plans p
WHERE p.price = 0
AND p.name <> '月会費（店舗により異なる）'
AND NOT EXISTS (
  SELECT 1 FROM subscriptions s WHERE s.plan_id = p.id
);

-- ----------------------------------------------------------------------------
-- 3) Figma / Gemini ロゴを同梱画像方式へ統一
--   旧: Figma は SVG 直リンク（ネイティブで描画不安定）、Gemini は 3840px PNG（過大）。
--   他サービスと同様 assets/services/{logo_key}.jpeg を参照させる。
--   （アプリ側マップ: components/subscriptions/serviceLogos.ts）
-- ----------------------------------------------------------------------------
UPDATE services
SET logo_key = 'gemini', logo_uri = NULL
WHERE id = 'b1000001-0001-4001-8001-000000000015';

UPDATE services
SET logo_key = 'figma', logo_uri = NULL
WHERE id = 'b1000001-0001-4001-8001-000000000020';
